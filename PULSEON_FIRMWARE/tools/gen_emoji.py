#!/usr/bin/env python3
"""Render common emoji from Noto Color Emoji into src/ui/PulseonEmoji.cpp/.h (24x24 ARGB8888)."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf"
SIZE = int(sys.argv[sys.argv.index("--size") + 1]) if "--size" in sys.argv else 16
EMOJI = ("😀😃😄😁😆😅😂🤣😊😇🙂😉😍🥰😘😋😎🤔😐🙄😏😴😢😭😩😫😤😡😱😨😰😓🤗🙏👍👎👌✌👏🙌💪👋🤝"
         "❤💔💕🔥✨⭐🎉🎂🎁🌹☀🌙☕🍕🍺🚗✅❌⚠😬😜🤪😔😞😕😳🥺😌😒🤩🥳😪😅🤷🤦🙈😈💯👀🎶")

font = ImageFont.truetype(FONT, 109)
items = []
for ch in dict.fromkeys(EMOJI):
    img = Image.new("RGBA", (136, 128), (0, 0, 0, 0))
    ImageDraw.Draw(img).text((0, 0), ch, font=font, embedded_color=True)
    box = img.getbbox()
    if box is None:
        print("skipped U+%04X (no glyph)" % ord(ch))
        continue
    img = img.crop(box)
    side = max(img.size)
    sq = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    sq.paste(img, ((side - img.width) // 2, (side - img.height) // 2))
    sq = sq.convert("RGBa").resize((SIZE, SIZE), Image.LANCZOS).convert("RGBA")
    data = bytearray()
    raw = sq.tobytes()
    for r, g, b, a in zip(raw[0::4], raw[1::4], raw[2::4], raw[3::4]):
        data += bytes((b, g, r, a))          # LVGL ARGB8888 is B,G,R,A in memory
    items.append((ord(ch), bytes(data)))

with open("src/ui/PulseonEmoji.h", "w") as h:
    h.write('#pragma once\n\n#include <lvgl.h>\n\nconstexpr int PULSEON_EMOJI_SIZE = %d;\n\n'
            '// Generated by tools/gen_emoji.py. Do not edit.\n'
            'void pulseonEmojiInit();\n'
            'const lv_image_dsc_t* pulseonEmojiFind(uint32_t codepoint);\n' % SIZE)

with open("src/ui/PulseonEmoji.cpp", "w") as c:
    c.write('// Generated by tools/gen_emoji.py. Do not edit.\n#include "PulseonEmoji.h"\n\nnamespace\n{\n')
    for i, (cp, data) in enumerate(items):
        c.write("const uint8_t map_%d[] = {\n" % i)
        for j in range(0, len(data), 24):
            c.write("    " + ",".join("0x%02x" % x for x in data[j:j + 24]) + ",\n")
        c.write("};\n")
    c.write("\nstruct Entry { uint32_t cp; const uint8_t* map; lv_image_dsc_t dsc; };\n")
    c.write("Entry table[%d] = {\n" % len(items))
    for i, (cp, _) in enumerate(items):
        c.write("    {0x%X, map_%d, {}},\n" % (cp, i))
    c.write("};\n} // namespace\n\n")
    c.write("void pulseonEmojiInit()\n{\n    for (Entry& e : table)\n    {\n"
            "        e.dsc.header.magic = LV_IMAGE_HEADER_MAGIC;\n"
            "        e.dsc.header.cf = LV_COLOR_FORMAT_ARGB8888;\n"
            "        e.dsc.header.flags = 0;\n"
            "        e.dsc.header.w = PULSEON_EMOJI_SIZE;\n"
            "        e.dsc.header.h = PULSEON_EMOJI_SIZE;\n"
            "        e.dsc.header.stride = PULSEON_EMOJI_SIZE * 4;\n"
            "        e.dsc.data_size = PULSEON_EMOJI_SIZE * PULSEON_EMOJI_SIZE * 4;\n"
            "        e.dsc.data = e.map;\n    }\n}\n\n")
    c.write("const lv_image_dsc_t* pulseonEmojiFind(uint32_t codepoint)\n{\n"
            "    for (const Entry& e : table)\n    {\n"
            "        if (e.cp == codepoint)\n        {\n            return &e.dsc;\n        }\n    }\n"
            "    return nullptr;\n}\n")
print("wrote %d emoji" % len(items))
