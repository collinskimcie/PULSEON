inline uint8_t uiThemeLoad()
{
    Preferences p;
    if (!p.begin("pulseon_ui", true))
    {
        return 0;
    }
    const uint8_t v = p.getUChar("theme", 0);
    p.end();
    return v < UI_PALETTE_COUNT ? v : 0;
}

inline void uiThemeSave(uint8_t v)
{
    Preferences p;
    if (p.begin("pulseon_ui", false))
    {
        p.putUChar("theme", v);
        p.end();
    }
}
